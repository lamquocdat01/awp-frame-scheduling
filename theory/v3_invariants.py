def get(d, path):
    for k in path:
        d = d[k]
    return d


def main():
    N = json.loads((REV / "numbers.json").read_text(encoding="utf-8"))
    tex = "".join((REV / f).read_text(encoding="utf-8") for f in
                  ("paper_v3.tex", "numbers.tex", "S1_theory_supplement.tex", "S2_empirical_supplement.tex")
                  if (REV / f).exists())
    rows, ok = [], 0
    for nid, desc, base, how in LOCKED:
        if how[0] == "tex":
            hit = how[1] in tex
            v3 = how[1] if hit else "(absent)"
        else:
            val = get(N, how[1])
            if isinstance(val, list):
                hit = all(abs(a - b) < 6e-4 for a, b in zip(val, how[2]))
            elif isinstance(val, bool):
                hit = val == how[2]
            else:
                hit = abs(float(val) - float(how[2])) < 6e-4
            v3 = val
        ok += hit
        rows.append(f"| {nid} | {desc} | {base} | {v3} | {'OK' if hit else 'MISMATCH'} |")
    blocks = (REV / "INVARIANTS_CHECK_blocks.txt").read_text(encoding="utf-8")
    md = ["# INVARIANTS_CHECK — AwP v3 vs. TPDS baseline (sha256 1a7341d4…)", "",
          "Generated by `code/v3_invariants.py` (numbers) and `code/v3_build_paper.py --check` (theorem blocks).", "",
          "## A. Theorem / definition / proof / remark blocks (byte level)", "", "```", blocks.strip(), "```", "",
          "**Intentional deviation (needs author approval):** `thmthree#1` + `proof#6` (Theorem 3 and its proof) are "
          "replaced by a corrected statement: HEDGE-GATE as specified by Algorithm 1 (block-aware advice arm, uniform draws) realises "
          "SAT-GATE and is Pareto-optimal in every regime; the 0.19 gap belongs to a naive overlapping split. Evidence: "
          "`code/v3_check_thm3_hedge.py`, `results/v3/thm3_hedge_audit.txt`, `P_LOG_03_v3.md`. All other 23 blocks are byte-identical.", "",
          "## B. 33 locked numbers + energy anchor", "",
          "| id | quantity | baseline | v3 | status |", "|---|---|---|---|---|"] + rows + ["",
          f"**{ok}/{len(LOCKED)} locked numbers carried unchanged.** Notes: N14 — the TPDS text attached 131,325 frames to the "
          "121-video corpus; it is the frame count of the 77 videos with ≥2 events (all 121 videos: "
          f"{N.get('c121_frames_all121')}); v3 states the correct referent. N27 — gate CI reproduces exactly; v3 adds the paired "
          "video-level bootstrap CI of the gap. N33 — value unchanged, attribution corrected (Theorem 3)."]
    sw = TOPIC / "results" / "v3" / "sweep_blockaware_summary.json"
    if sw.exists():  # P3C: fig5 / S2.5 re-run with the block-aware split of Algorithm 1
        S = json.loads(sw.read_text(encoding="utf-8"))
        md += ["", "## C. Real-data trust-dial sweep (fig5, S2.5) — block-aware re-run (P3C)", "",
               "`code/v3_sweep_blockaware.py`, same corpus/order/seeds as the TPDS sweep. Endpoints λ ∈ {0, 1} must equal "
               "the TPDS numbers (invariant); 0 < λ < 1 are new numbers (Algorithm 1 v3).", ""] + \
              [f"- {x}" for x in S["invariants"]] + ["",
               f"**{'PASS' if S['invariant_failures'] == 0 else 'FAIL'}: {S['invariant_failures']} invariant failure(s).** "
               f"Intermediate λ (block-aware − frame-level): {S['intermediate_lambda']}."]
    atomic_write_text(REV / "INVARIANTS_CHECK.md", "\n".join(md) + "\n", encoding="utf-8")
    print(f"{ok}/{len(LOCKED)} locked numbers OK")


if __name__ == "__main__":
    main()
